import { readdir, writeFile } from "node:fs/promises";
const collect = async (directory, prefix) => {
  const entries = await readdir(directory, { withFileTypes: true }).catch(() => []);
  const files = await Promise.all(
    entries.map((entry) =>
      entry.isDirectory()
        ? collect(`${directory}/${entry.name}`, `${prefix}/${entry.name}`)
        : [`${prefix}/${entry.name}`],
    ),
  );
  return files.flat();
};
const staticFiles = (await collect(".next/static", "/_next/static")).filter((path) =>
  /\.(js|css|woff2?|ttf)$/.test(path),
);
const logos = await collect("public/merchants", "/merchants");
const version = Date.now().toString(36);
const shell = [
  "/",
  "/privacy",
  "/terms",
  "/offline.html",
  "/manifest.webmanifest",
  "/manifest-dark.webmanifest",
  "/brand/mark.svg",
  "/brand/icon-192.png",
  "/brand/icon-512.png",
  "/brand/apple-touch-icon.png",
  "/brand/maskable-512.png",
  "/images/renewal-loop.webp",
  "/sample-statement.csv",
  "/pdf.worker.min.mjs",
  ...logos,
  ...staticFiles,
];
await writeFile(
  "public/sw.js",
  `/* Generated by build-sw.mjs. Never cache auth or financial network responses. */
const CACHE='substition-${version}';
const SHELL=${JSON.stringify(shell)};
self.addEventListener('install',event=>{event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(SHELL)));});
self.addEventListener('activate',event=>{event.waitUntil((async()=>{for(const name of await caches.keys())if(name.startsWith('substition-')&&name!==CACHE)await caches.delete(name);await self.clients.claim();})());});
self.addEventListener('message',event=>{if(event.data==='SKIP_WAITING')self.skipWaiting();});
self.addEventListener('fetch',event=>{
  const request=event.request,url=new URL(request.url);
  if(request.method!=='GET'||url.origin!==self.location.origin||url.pathname.startsWith('/api/')||url.pathname.startsWith('/sign-in'))return;
  if(request.mode==='navigate'){
    event.respondWith((async()=>{try{const response=await fetch(request);if(response.ok&&['/','/privacy','/terms'].includes(url.pathname)){const cache=await caches.open(CACHE);await cache.put(url.pathname,response.clone());}return response;}catch{const cache=await caches.open(CACHE);return await cache.match(url.pathname)||await cache.match('/offline.html');}})());return;
  }
  if(url.pathname.startsWith('/_next/static/')||url.pathname.startsWith('/brand/')||url.pathname.startsWith('/merchants/')||url.pathname.startsWith('/images/')||url.pathname==='/pdf.worker.min.mjs'||url.pathname.endsWith('.webmanifest')){
    event.respondWith((async()=>{const cache=await caches.open(CACHE);const found=await cache.match(request);if(found)return found;const response=await fetch(request);if(response.ok)await cache.put(request,response.clone());return response;})());
  }
});`,
);
console.log(
  `Offline shell prepared: ${shell.length} local assets. AI weights require separate opt-in download.`,
);
